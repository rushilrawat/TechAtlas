def main() -> None:
    graph = json.loads(GRAPH.read_text(encoding="utf-8"))
    ids = {n["id"] for n in graph["nodes"]}
    pairs = {frozenset((e["source"], e["target"])) for e in graph["edges"]}
    journeys = json.loads(JOURNEYS.read_text(encoding="utf-8"))
    have = {j["title"] for j in journeys}
    problems = []
    for path in PATHS:
        steps = [s["id"] for s in path["steps"]]
        for s in steps:
            if s not in ids:
                problems.append(f"{path['title']}: missing node {s}")
        for a, b in zip(steps, steps[1:], strict=False):
            if frozenset((a, b)) not in pairs:
                problems.append(f"{path['title']}: no edge {a} -- {b}")
    if problems:
        raise SystemExit("\n".join(problems))
    added = [p_ for p_ in PATHS if p_["title"] not in have]
    JOURNEYS.write_text(json.dumps(journeys + added, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"added {len(added)} guided paths ({len(journeys) + len(added)} total)")


if __name__ == "__main__":
    main()
