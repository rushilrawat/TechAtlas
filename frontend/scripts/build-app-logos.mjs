/* global console, process */
// Writes src/content/appLogos.ts: one brand mark per famous app, taken from Simple Icons
// (CC0, https://simpleicons.org). Only the 40-odd marks the Apps panel needs are kept, so
// the chunk stays small; it loads on demand the first time a logo is drawn.
// Apps with no mark in Simple Icons (some brands asked to be removed) get a monogram tile.
// Run after adding an app to data/seed/apps.json:  node scripts/build-app-logos.mjs
// Logos are trademarks of their owners and are shown only to identify each company.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as icons from "simple-icons";

// App id (apps.json) -> Simple Icons slug, where it differs or needs a pick.
const SLUG = {
  "khan-academy": "khanacademy",
  "x-twitter": "x",
  "google-search": "google",
  "stack-overflow": "stackoverflow",
};

const root = join(import.meta.dirname, "..");
const apps = JSON.parse(readFileSync(join(root, "..", "data", "seed", "apps.json"), "utf8"));
const bySlug = new Map(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = {};
const missing = [];
for (const app of apps) {
  const icon = bySlug.get(SLUG[app.id] ?? app.id);
  if (icon) out[app.id] = { hex: icon.hex, path: icon.path };
  else missing.push(app.id);
}
const lines = Object.entries(out).map(([id, l]) => `  ${JSON.stringify(id)}: { hex: "${l.hex}", path: ${JSON.stringify(l.path)} },`);
writeFileSync(join(root, "src", "content", "appLogos.ts"), `// Generated by scripts/build-app-logos.mjs from Simple Icons (CC0). Do not edit by hand.
// Logos are trademarks of their owners, shown only to identify each company.
// No mark available (shown as a monogram): ${missing.join(", ") || "none"}.
export interface BrandMark { hex: string; path: string }
export const APP_LOGOS: Record<string, BrandMark> = {
${lines.join("\n")}
};
`);
console.log(`wrote ${Object.keys(out).length} logos; monogram for: ${missing.join(", ") || "none"}`);
process.exit(0);
